// Якоря доверия: отпечатки корневых сертификатов аттестации.
//
// Цепочка сертификатов, приложенная к съёмке, признаётся настоящей, только
// если ПОСЛЕДНЕЕ её звено совпадает по отпечатку SHA-256 с одним из
// перечисленных здесь. Сверка по отпечатку — утверждение более сильное, чем
// проверка срока действия: она говорит «это в точности тот корень», а не
// «этот сертификат ещё не истёк».
//
// Именно поэтому срок действия к последнему звену не применяется. Google
// перевыпустил свой корень аттестации, сохранив прежний серийный номер
// (старый действовал 2016 — 24.05.2026, новый 2022 — 2042), и прямо
// рекомендует доверять цепочке к этому корню независимо от срока. Так же
// поступает и стандарт X.509: срок действия якоря доверия не проверяется,
// потому что проверять его некому — он подписан сам собой.
//
// Список должен совпадать с браузерной проверкой: обе стороны меняются
// только вместе.
